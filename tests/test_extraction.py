# ---------------------------------------------------------------- failure modes


def test_image_only_pdf_returns_empty_rather_than_raising():
    """A scan parses fine — it simply has no text layer. The caller decides."""
    result = extract(SCANNED, read(SCANNED))
    assert result.layout == "empty"
