# ---------------------------------------------------------------- load_resume_text


def test_load_resume_text_hands_the_profiler_a_plain_string():
    source = load_resume_text(ONE_COLUMN, read(ONE_COLUMN))
    assert source.text.startswith("Ravi Menon")
    assert not source.was_clipped
    assert source.extraction.layout == "single-column"


def test_load_resume_text_refuses_a_scan_before_any_model_call():
    """The one case that must never reach the model: an empty string costs
    tokens and comes back as a confidently invented profile."""
    with pytest.raises(NoTextLayer) as caught:
        load_resume_text(SCANNED, read(SCANNED))
    assert "scan" in str(caught.value)


def test_load_resume_text_reports_clipping_instead_of_truncating_silently(monkeypatch):
    long_text = "Ravi Menon is a backend engineer. " * 4000
    monkeypatch.setattr(
        extraction, "extract", lambda *_: Extraction(long_text, 1, "single-column")
    )
    source = load_resume_text("resume.pdf", b"ignored")
    assert len(source.text) == MAX_RESUME_CHARS
    assert source.was_clipped
    assert source.clipped_chars == len(long_text) - MAX_RESUME_CHARS


def test_extracted_text_is_accepted_by_the_profiler_input_check():
    """Step [0] output is valid step [1] input — the seam holds without a call."""
    source = load_resume_text(ONE_COLUMN, read(ONE_COLUMN))
    assert check_resume(source.text) == source.text.strip()
