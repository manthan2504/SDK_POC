def read(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def text_of(name: str) -> str:
    return extract(name, read(name)).text


# ---------------------------------------------------------------- _clean


def test_clean_keeps_line_structure_but_collapses_runs():
    assert _clean("a  b\t c\r\n\r\n\r\n\r\nd  ") == "a b c\n\nd"


def test_clean_maps_unmappable_glyphs_to_a_bullet():
    """pdfminer emits (cid:NNN) for a glyph it cannot map — Symbol/Wingdings
    bullets hit this constantly. Left alone it reaches the model as junk."""
    assert _clean("(cid:127) Built a pipeline") == "• Built a pipeline"


def test_clean_strips_control_characters_including_nul():
    assert _clean("Ravi\x00 Menon\x07") == "Ravi Menon"


def test_clean_leaves_resume_punctuation_alone():
    line = "Mar 2021 – Present | 34% | +91 90000 11111 | a.b@example.invalid"
    assert _clean(line) == line


# ---------------------------------------------------------------- _find_gutter


def word(x0: float, x1: float, top: float = 100.0) -> dict:
    return {"x0": x0, "x1": x1, "top": top, "bottom": top + 10.0}


def test_find_gutter_returns_none_without_words():
    assert _find_gutter([], 600.0, 800.0) is None


def test_find_gutter_finds_a_real_two_column_gap():
    words = [word(40, 240) for _ in range(20)] + [word(330, 520) for _ in range(20)]
    found = _find_gutter(words, 600.0, 800.0)
    assert found is not None
    gutter_x, cut = found
    assert 240 < gutter_x < 330
    assert cut == 0.0


def test_find_gutter_ignores_a_narrow_accidental_channel():
    """The Caliber bug: on a single-column page, inter-word spaces line up and a
    ~4pt channel wins, after which straddling words are emitted twice in halves.
    A column gap is tens of points wide; anything narrower is an accident."""
    words = [word(40, 296) for _ in range(20)] + [word(300, 520) for _ in range(20)]
    assert _find_gutter(words, 600.0, 800.0) is None


def test_find_gutter_needs_a_real_share_of_words_on_both_sides():
    words = [word(40, 240) for _ in range(40)] + [word(330, 520) for _ in range(2)]
    assert _find_gutter(words, 600.0, 800.0) is None


