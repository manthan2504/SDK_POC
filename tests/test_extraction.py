def test_a_tightly_spaced_page_still_yields_separate_words():
    body = text_of(TIGHT_SPACING)
    assert "Solvent Labs India, Software Engineer" in body
    assert "Bachelor of Engineering, Ghatkopar Institute of Technology, 2019" in body
    assert "Strong focus on system optimization, profiling and release hygiene." in body


def test_a_tightly_spaced_page_is_still_read_as_one_column():
    result = extract(TIGHT_SPACING, read(TIGHT_SPACING))
    assert result.layout == "single-column"
    assert result.is_usable


def test_with_pdfplumbers_default_tolerance_the_same_page_loses_its_spaces(monkeypatch):
    """Pins `_TOLERANCE` (RULEBOOK §16 O21). Most PDFs store no space characters;
    at the 3 pt default this page's 2.2 pt word gaps read as intra-word, the text
    still passes every check here, and the damage only lands downstream, where
    the Profiler verifies each claim as a verbatim substring."""
    monkeypatch.setattr(extraction, "_TOLERANCE", {})
    fused = text_of(TIGHT_SPACING)
    assert "BachelorofEngineering" in fused
    assert "Bachelor of Engineering" not in fused
    assert "SoftwareEngineer" in fused


def test_a_flat_tolerance_would_shatter_the_heading_where_a_ratio_holds_it(monkeypatch):
    """Why the constant is a ratio and not a flat point value: the 20 pt name on
    this page is tracked 2.0 pt apart, which a flat 1.5 pt reads as word gaps,
    while 0.15 x 20 pt leaves 3.0 pt of headroom. Both settings split the 10 pt
    body correctly — only the ratio survives both font sizes."""
    assert "Priya Deshmukh" in text_of(TIGHT_SPACING)
    monkeypatch.setattr(extraction, "_TOLERANCE", {"x_tolerance": 1.5})
    assert "P r i y a D e s h m u k h" in text_of(TIGHT_SPACING)


@pytest.mark.parametrize("name", [ONE_COLUMN, TWO_COLUMN_INTERLEAVED])
def test_every_pdfplumber_call_is_given_the_same_tolerance(name, monkeypatch):
    """The column path crops the page and extracts again; if that call kept the
    library default, a two-column page would decide where words begin on
    different rules from a one-column one."""
    from pdfplumber.page import Page

    seen: list[dict] = []
    for method in ("extract_text", "extract_words"):
        original = getattr(Page, method)

        def spy(self, *args, _original=original, **kwargs):
            seen.append(kwargs)
            return _original(self, *args, **kwargs)

        monkeypatch.setattr(Page, method, spy)

    extract(name, read(name))
    assert seen
    assert all(call.get("x_tolerance_ratio") == 0.15 for call in seen), seen


