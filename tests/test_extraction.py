@pytest.mark.parametrize("name", [TRUNCATED, NOT_A_PDF])
def test_corrupt_pdf_becomes_one_domain_error(name):
    with pytest.raises(UnreadableDocument) as caught:
        extract(name, read(name))
    assert "corrupt" in str(caught.value)


def test_unsupported_extension_is_refused_before_parsing():
    with pytest.raises(UnsupportedFileType):
        extract("resume.txt", b"plain text is not an upload path")


def test_oversized_upload_is_refused_before_parsing():
    with pytest.raises(FileTooLarge):
        extract("resume.pdf", b"x" * (extraction.MAX_UPLOAD_BYTES + 1))


def test_every_failure_is_still_a_value_error():
    """Caliber's callers catch ValueError; the subclasses must not break them."""
    for error in (UnsupportedFileType, FileTooLarge, UnreadableDocument, NoTextLayer):
        assert issubclass(error, ValueError)


